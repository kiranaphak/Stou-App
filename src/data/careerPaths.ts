/**
 * Helper to get career paths based on schoolCode, programName, and major/track names
 */
export function getCareerPathsForProgram(
  schoolCode: string,
  programName?: string,
  matchedMajorNames: string[] = []
): {
  primaryChips: string[];
  allCareers: string[];
  notes?: string[];
} {
  const careerKey = SCHOOL_CODE_TO_CAREER_KEY[schoolCode];
  if (!careerKey || !CAREER_PATHS_2569[careerKey]) {
    return {
      primaryChips: ['งานสายตรงตามสาขาวิชา', 'งานพัฒนาต่อยอดวิชาชีพ', 'ผู้ประกอบการ'],
      allCareers: ['งานสายตรงตามสาขาวิชา', 'งานพัฒนาต่อยอดวิชาชีพ', 'ผู้ประกอบการ'],
    };
  }

  const schoolData = CAREER_PATHS_2569[careerKey];
  let matchedCareers: string[] = [];

  // 1. Try to find careers for matched majors/tracks first
  if (schoolData.majorCareerPaths && matchedMajorNames.length > 0) {
    for (const majorName of matchedMajorNames) {
      // Find key matching majorName (either exact or substring match)
      const foundKey = Object.keys(schoolData.majorCareerPaths).find((k) =>
        majorName.includes(k) || k.includes(majorName)
      );
      if (foundKey && schoolData.majorCareerPaths[foundKey]) {
        const list = schoolData.majorCareerPaths[foundKey];
        list.forEach((item) => {
          if (!matchedCareers.includes(item)) {
            matchedCareers.push(item);
          }
        });
      }
    }
  }

  // 2. If no major careers found or needed more, check programCareerPaths
  if (matchedCareers.length === 0 && schoolData.programCareerPaths && programName) {
    const foundProgKey = Object.keys(schoolData.programCareerPaths).find((k) =>
      programName.includes(k) || k.includes(programName)
    );
    if (foundProgKey && schoolData.programCareerPaths[foundProgKey]) {
      const list = schoolData.programCareerPaths[foundProgKey];
      list.forEach((item) => {
        if (!matchedCareers.includes(item)) {
          matchedCareers.push(item);
        }
      });
    }
  }

  // 3. If still empty, check generalCareerPaths
  if (matchedCareers.length === 0 && schoolData.generalCareerPaths) {
    matchedCareers = [...schoolData.generalCareerPaths];
  }

  // 4. Fallback from any available list in this school
  if (matchedCareers.length === 0) {
    if (schoolData.majorCareerPaths) {
      const allMajorLists = Object.values(schoolData.majorCareerPaths).flat();
      matchedCareers = Array.from(new Set(allMajorLists));
    } else if (schoolData.programCareerPaths) {
      const allProgLists = Object.values(schoolData.programCareerPaths).flat();
      matchedCareers = Array.from(new Set(allProgLists));
    }
  }

  // Cap primary chips at 3-5 items
  const primaryChips = matchedCareers.slice(0, 5);

  return {
    primaryChips,
    allCareers: matchedCareers,
    notes: schoolData.notes,
  };
}
